    case_ "stash: push" fx_dirty ':' 'G stash; G stash list'
    case_ "stash: push -m" fx_dirty ':' 'G stash push -m "my message"; G stash list'
    case_ "stash: push -u" fx_dirty ':' 'G stash push -u; G stash list'
    case_ "stash: push -u -m" fx_dirty ':' 'G stash push -u -m "with untracked"'
    case_ "stash: push --keep-index" fx_dirty ':' 'G stash push --keep-index'
    case_ "stash: push -k -u" fx_dirty ':' 'G stash push -k -u'
    case_ "stash: save message" fx_dirty ':' 'G stash save "old style message"'
    case_ "stash: push -q" fx_dirty ':' 'G stash push -q; G stash list'
    case_ "stash: nothing to save" fx_base ':' 'G stash; G stash list'
    case_ "stash: only untracked without -u" fx_base 'echo n > new.txt' 'G stash'
    case_ "stash: only untracked with -u" fx_base 'echo n > new.txt' 'G stash -u'
    case_ "stash: empty repository" fx_empty ':' 'G stash'
    case_ "stash: detached head" fx_dirty 'git checkout -q --detach' 'G stash; G stash list'
    case_ "stash: unmerged" fx_conflict ':' 'G stash'
    case_ "stash: staged new file and deletion" fx_base 'echo n > new.txt; git add new.txt; git rm -q b.txt' 'G stash; G stash apply --index'
    case_ "stash: mode change" fx_base 'chmod +x a.txt' 'G stash; G stash pop'
    case_ "stash: pop" fx_dirty 'git stash -q' 'G stash pop; G stash list'
    case_ "stash: pop --index" fx_dirty 'git stash -q' 'G stash pop --index'
    case_ "stash: pop -u" fx_dirty 'git stash -q -u' 'G stash pop; G stash list'
    case_ "stash: pop --index -u" fx_dirty 'git stash -q -u' 'G stash pop --index'
    case_ "stash: apply keeps the entry" fx_dirty 'git stash -q' 'G stash apply; G stash list'
    case_ "stash: apply -q" fx_dirty 'git stash -q' 'G stash apply -q; G stash pop -q'
    case_ "stash: apply a numbered entry" fx_dirty 'git stash -q; echo again >> a.txt; git stash -q' 'G stash apply stash@{1}; G stash list'
    case_ "stash: apply by number" fx_dirty 'git stash -q; echo again >> a.txt; git stash -q' 'G stash apply 1'
    case_ "stash: pop by number" fx_dirty 'git stash -q; echo again >> a.txt; git stash -q' 'G stash pop 1; G stash list'
    case_ "stash: pop with no entries" fx_base ':' 'G stash pop; G stash apply; G stash drop; G stash show'
    case_ "stash: pop onto a conflicting change" fx_base 'echo m >> a.txt; git stash -q; echo other >> a.txt; git commit -qam moved' 'G stash pop; G stash list'
    case_ "stash: apply onto a conflicting change" fx_base 'echo m >> a.txt; git stash -q; echo other >> a.txt; git commit -qam moved' 'G stash apply'
    case_ "stash: apply onto a clean merge" fx_branches 'echo m >> g.txt; git stash -q; echo more > h.txt; git commit -qam moved' 'G stash apply; G stash drop'
    case_ "stash: apply with local changes in the way" fx_dirty 'git stash -q; echo other >> a.txt' 'G stash apply'
    case_ "stash: apply with an untracked file in the way" fx_dirty 'git stash -q -u; echo other > un.txt' 'G stash apply'
    case_ "stash: drop" fx_dirty 'git stash -q; echo again >> a.txt; git stash -q' 'G stash drop; G stash list'
    case_ "stash: drop a numbered entry" fx_dirty 'git stash -q; echo again >> a.txt; git stash -q' 'G stash drop stash@{1}; G stash list'
    case_ "stash: drop -q" fx_dirty 'git stash -q' 'G stash drop -q; G stash list'
    case_ "stash: drop an entry that is not there" fx_dirty 'git stash -q' 'G stash drop stash@{3}; G stash drop 7'
    case_ "stash: clear" fx_dirty 'git stash -q; echo again >> a.txt; git stash -q' 'G stash clear; G stash list; G stash clear'
    case_ "stash: list" fx_dirty 'git stash -q; echo again >> a.txt; git stash -q -m second; echo n3 >> b.txt; git stash -q' 'G stash list'
    case_ "stash: show" fx_dirty 'git stash -q' 'G stash show'
    case_ "stash: show -p" fx_dirty 'git stash -q' 'G stash show -p'
    case_ "stash: show --stat -p" fx_dirty 'git stash -q' 'G stash show --stat -p'
    case_ "stash: show --name-only" fx_dirty 'git stash -q' 'G stash show --name-only; G stash show --name-status'
    case_ "stash: show numbered" fx_dirty 'git stash -q; echo again >> a.txt; git stash -q' 'G stash show stash@{1}; G stash show 1 -p'
    case_ "stash: show -u" fx_dirty 'git stash -q -u' 'G stash show -u; G stash show --include-untracked -p'
    case_ "stash: show --only-untracked" fx_dirty 'git stash -q -u' 'G stash show --only-untracked'
    case_ "stash: show with stash.showPatch" fx_dirty 'git stash -q; git config stash.showPatch true' 'G stash show'
    case_ "stash: branch" fx_dirty 'git stash -q' 'G stash branch fromstash; G stash list'
    case_ "stash: branch of an older entry" fx_dirty 'git stash -q; git commit -q --allow-empty -m e; echo q >> a.txt; git stash -q' 'G stash branch old stash@{1}'
    case_ "stash: branch name taken" fx_dirty 'git stash -q' 'G stash branch side; G stash list'
    case_ "stash: branch with untracked" fx_dirty 'git stash -q -u' 'G stash branch ub'
    case_ "stash: from a subdirectory" fx_dirty ':' 'cd dir; G stash; G stash pop'
    case_ "stash: create and store" fx_dirty ':' 'id=$(G stash create); G stash store -m stored "$(git stash create 2>/dev/null)"; G stash list'
    case_ "stash: unknown subcommand" fx_dirty ':' 'G stash frobnicate'
    case_ "stash: deleted file" fx_base 'rm b.txt' 'G stash; G stash pop'
    case_ "stash: pop twice" fx_dirty 'git stash -q; echo q >> a.txt; git stash -q' 'G stash pop; G stash reset 2>/dev/null; G stash pop'
fi
